export type IconName = (typeof PICKABLE_ICONS)[number] | (typeof OWN_ICONS)[number]

export const ALL_ICONS: readonly IconName[] = [...PICKABLE_ICONS, ...OWN_ICONS]

export function isIconName(value: unknown): value is IconName {
  return typeof value === 'string' && (ALL_ICONS as readonly string[]).includes(value)
}
